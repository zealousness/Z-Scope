API_PROMPT = (
    "Public API declared in a header file. Audit caller-controlled arguments and API contract misuse. "
    "This header API is an external scan root: zero repository callers, absence from main, or absence "
    "of a separate worker/start wrapper is expected and must not be treated as dead code by itself. "
    "Treat this as an externally reachable facade: follow its callees and callback/worker paths to the "
    "actual internal source/sink operations, and report the concrete vulnerable callee location rather "
    "than stopping at the wrapper call site."
)
COMM_PROMPT = (
    "Communication or IPC entry. Treat bytes read from peers/shared channels as untrusted. "
    "Audit framing, length checks, return-value handling, and trust boundaries before parsing, "
    "dispatch, copies, indexing, or deserialization. If the received data or derived length is "
    "returned, written through an out-parameter, stored in shared/session state, or otherwise "
    "consumed by callers, use get_callers to inspect caller-side parsing and validation instead "
    "of stopping at the low-level read wrapper."
)
THREAD_PROMPT = "Thread entry or thread creator. Audit stack lifetime, shared state, lock ordering, and handoff ownership."
INPUT_PROMPT = (
    "User-controlled input entry. Treat file, environment, CLI, device, and stdin data as untrusted. "
    "Audit parsing, size conversion, range checks, termination, and resource cleanup before the data "
    "feeds copies, indexing, allocation sizes, dispatch, paths, or commands. If the input buffer, "
    "string, parsed value, or derived length is returned, written through an out-parameter, stored "
    "globally, or consumed by callers, use get_callers to inspect caller-side validation and sinks."
)


@dataclass
class EntryCandidate:
    function_name: str
    exposure: str
    reasons: List[str] = field(default_factory=list)
    file_path: str = ""
    signature: str = ""
    line: int = 0
    custom_prompt: str = ""
    confidence: float = 0.5
    selection_status: str = "selected"
    deferred_reason: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "function_name": self.function_name,
            "exposure": self.exposure,
            "reasons": self.reasons,
            "file_path": self.file_path,
            "signature": self.signature,
            "line": self.line,
            "custom_prompt": self.custom_prompt,
            "confidence": self.confidence,
            "selection_status": self.selection_status,
            "candidate_disposition": (
                "deferred_budget" if self.selection_status == "deferred_budget" else "selected"
            ),
            "deferred_reason": self.deferred_reason,
        }

    def to_function_entry(self) -> FunctionEntry:
        return FunctionEntry(
            function_name=self.function_name,
            custom_prompt=self.custom_prompt,
            file_path=self.file_path or None,
            signature=self.signature or None,
            exposure=self.exposure,
            reasons=list(self.reasons),
        )


@dataclass
class EntryDiscoveryResult:
    exposure_kind: str
    candidates: List[EntryCandidate]
    summary: Dict[str, int]
    notes: List[str] = field(default_factory=list)
    deferred_candidates: List[EntryCandidate] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "exposure_kind": self.exposure_kind,
            "summary": self.summary,
            "notes": self.notes,
            "candidates": [c.to_dict() for c in self.candidates],
            "deferred_candidates": [candidate.to_dict() for candidate in self.deferred_candidates],
        }

    def to_function_entries(self) -> List[FunctionEntry]:
        return [candidate.to_function_entry() for candidate in self.candidates]

    def to_entry_functions_payload(self) -> Dict[str, Any]:
        return {
            "description": "Auto-generated by Z-SCOPE entry discovery.",
            "discovery": {
                "exposure_kind": self.exposure_kind,
                "summary": self.summary,
                "notes": self.notes,
                "deferred_budget_count": len(self.deferred_candidates),
                "deferred_candidates": [
                    candidate.to_dict() for candidate in self.deferred_candidates
                ],
            },
            "functions": [
                {
                    "function_name": candidate.function_name,
                    "file_path": candidate.file_path,
                    "signature": candidate.signature,
                    "custom_prompt": candidate.custom_prompt,
                    "exposure": candidate.exposure,
                    "reasons": candidate.reasons,
                    "line": candidate.line,
                    "confidence": candidate.confidence,
                }
                for candidate in self.candidates
            ],
        }


