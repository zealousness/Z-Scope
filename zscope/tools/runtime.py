"""Runtime adapter for policy-controlled execution of registered tools."""

import json
import logging
import time
from copy import deepcopy
from typing import Any, Callable, Dict, Iterable, List, Optional, TYPE_CHECKING

from ..common.cancellation import CancellationError
from ..framework.base import BaseTool
from ..snapshots.store import SnapshotStore
from .policy import ToolPolicy
from .registry import build_tool_registry
from .contracts import ContractTool, invalid_request, tool_result
from .source_access import source_lines

if TYPE_CHECKING:
    from ..config.user_config_store import UserConfigStore
    from ..retrieval.code_index import CodeIndex

logger = logging.getLogger(__name__)


class ToolsRuntime:
    """Expose registered tools through one policy and execution pipeline."""

    def __init__(
        self,
        code_index: "CodeIndex",
        snapshot_store: SnapshotStore,
        user_config: Optional["UserConfigStore"] = None,
        tool_policy: Optional[ToolPolicy] = None,
        *,
        tools: Optional[Iterable[BaseTool]] = None,
        snapshot_resolver: Optional[Any] = None,
        candidate_ledger: Any = None,
        access_profile: str = "default",
    ) -> None:
        self.code_index = code_index
        if access_profile not in {"default", "read_only", "candidate_blind"}:
            raise ValueError("Unknown tool access profile")
        if access_profile != "default" and tools is not None:
            raise ValueError("Read-only profiles require the controlled tool registry")
        self.access_profile = access_profile
        self.snapshot_store = snapshot_store
        self.user_config = user_config
        self.tool_policy = tool_policy or ToolPolicy.allow_all()
        registry = (
            build_tool_registry(
                code_index,
                snapshot_store,
                user_config,
                snapshot_resolver=snapshot_resolver,
                candidate_ledger=candidate_ledger,
                access_profile=access_profile,
            )
            if tools is None
            else self._registry_from_tools(tools)
        )
        self._tools_by_name = registry
        self._schema_cache: Optional[Dict[str, Dict[str, Any]]] = None
        self._read_code_cache: List[tuple[Dict[str, Any], Dict[str, Any]]] = []
        self._read_code_identity: Any = None

    @staticmethod
    def _registry_from_tools(tools: Iterable[BaseTool]) -> Dict[str, BaseTool]:
        registry: Dict[str, BaseTool] = {}
        for tool in tools:
            if tool.name in registry:
                raise ValueError(f"Duplicate tool name: {tool.name}")
            registry[tool.name] = tool
        return registry

    def get_tools_schema(self, *, apply_policy: bool = True) -> List[Dict[str, Any]]:
        """Return schemas generated by the registered tool objects."""
        schemas = [tool.get_schema() for tool in self._tools_by_name.values()]
        if self.access_profile == "candidate_blind":
            schemas = [s for s in schemas if s["function"]["name"] != "query_static_findings"]
        if apply_policy:
            return self.tool_policy.filter_tool_schemas(schemas)
        return schemas

    def _tool_schema_by_name(self) -> Dict[str, Dict[str, Any]]:
        if self._schema_cache is None:
            self._schema_cache = {
                name: tool.get_schema() for name, tool in self._tools_by_name.items()
            }
        return self._schema_cache

    def execute_tool(
        self,
        tool_name: str,
        arguments: Any,
        *,
        actor: str = "tools_runtime",
        enforce_policy: bool = True,
    ) -> Dict[str, Any]:
        """Execute a registered tool by name."""
        logger.debug("Executing tool %r", tool_name)
        try:
            effective_args = arguments
            tool = self._tools_by_name.get(tool_name)

            if not isinstance(effective_args, dict):
                if tool is not None:
                    validation_error = tool.validate_arguments(effective_args)
                    if validation_error:
                        return validation_error
                return (
                    invalid_request(
                        code="schema_validation_failed",
                        path="$",
                        message="Tool arguments must be a JSON object",
                    )
                    if isinstance(tool, ContractTool)
                    else {
                        "success": False,
                        "error": "Tool arguments must be a JSON object; please correct the payload and retry.",
                    }
                )

            if tool is None:
                return invalid_request(
                    code="unknown_tool",
                    path="name",
                    message=f"Unknown tool: {tool_name}",
                    retryable=False,
                )

            validation_error = tool.validate_arguments(effective_args)
            if validation_error:
                if enforce_policy:
                    # Preserve the security audit trail for malformed attempts,
                    # while keeping their public status as invalid_request.
                    self.tool_policy.enforce_tool(
                        tool_name,
                        effective_args,
                        schema=self._tool_schema_by_name().get(tool_name),
                        actor=actor,
                    )
                return validation_error

            if self.access_profile == "candidate_blind" and tool_name == "query_static_findings":
                return tool_result(
                    status="forbidden",
                    data=None,
                    error={
                        "code": "profile_denied",
                        "path": None,
                        "message": "This tool is not available in the candidate-blind profile.",
                        "retryable": False,
                    },
                )
            if enforce_policy:
                policy_error = self.tool_policy.enforce_tool(
                    tool_name,
                    effective_args,
                    schema=self._tool_schema_by_name().get(tool_name),
                    actor=actor,
                )
                if policy_error:
                    if isinstance(tool, ContractTool):
                        return tool_result(
                            status="forbidden",
                            data=None,
                            coverage_level="unsupported",
                            error={
                                "code": "policy_denied",
                                "path": None,
                                "message": str(
                                    policy_error.get("error") or "Tool use blocked by policy"
                                ),
                                "retryable": False,
                            },
                        )
                    return policy_error

            if self.access_profile != "default" and tool_name in {
                "query_code_graph",
                "trace_data_flow",
            }:
                return tool_result(
                    status="unavailable",
                    data=None,
                    missing=["verified_cached_program_facts"],
                    next_actions=[
                        "Read current source; graph/flow queries require verified existing input identity."
                    ],
                )

            start = time.perf_counter()
            if tool_name == "read_code":
                identity_getter = getattr(tool, "cache_identity", None)
                if callable(identity_getter):
                    identity = identity_getter(effective_args)
                    if identity != self._read_code_identity:
                        self._read_code_cache.clear()
                    self._read_code_identity = identity
                cached_read = self._cached_read_code(effective_args)
                if cached_read is not None:
                    cached_read = self.finalize_result(tool, cached_read)
                    self._run_post_hooks(
                        tool_name,
                        effective_args,
                        cached_read,
                        actor=actor,
                        enforce_policy=enforce_policy,
                        start=start,
                    )
                    return cached_read
            result = tool.execute(effective_args)
            if (
                getattr(self.code_index, "cache_only", False)
                and tool_name == "search_code"
                and effective_args.get("scope", "symbols") == "symbols"
                and result.get("success")
            ):
                result["status"] = (
                    "partial" if result.get("data", {}).get("symbols") else "unavailable"
                )
                result["coverage"]["level"] = result["status"]
                result["coverage"]["missing"] = ["index_freshness_unverified"]
                result["warnings"].append(
                    "Cached symbols are navigation hints; the index input identity is unverified."
                )
            result = self.finalize_result(tool, result)
            if tool_name == "read_code" and result.get("success") is True:
                self._read_code_cache.append((dict(effective_args), deepcopy(result)))
                self._read_code_cache = self._read_code_cache[-64:]
            self._run_post_hooks(
                tool_name,
                effective_args,
                result,
                actor=actor,
                enforce_policy=enforce_policy,
                start=start,
            )
            return result
        except CancellationError:
            raise
        except Exception as exc:
            return self.execution_failure(tool_name, exc)

    @staticmethod
    def execution_failure(tool_name: str, exc: Exception) -> Dict[str, Any]:
        """Expose a stable failure category; provider messages may contain credentials."""
        logger.error("Tool %s failed: %s", tool_name, type(exc).__name__)
        return tool_result(
            status="internal_error",
            data=None,
            coverage_level="unavailable",
            error={
                "code": "tool_execution_failed",
                "path": None,
                "message": f"Tool execution failed ({type(exc).__name__}).",
                "retryable": False,
            },
        )

    @staticmethod
    def finalize_result(tool: BaseTool, result: Dict[str, Any]) -> Dict[str, Any]:
        """Apply the same output boundary to Agent calls, runtime calls and cache hits."""
        if not isinstance(tool, ContractTool):
            return result
        result = ToolsRuntime._enforce_result_limit(result)
        error = tool.validate_result(result)
        if not error:
            return result
        logger.error("Tool %s returned a result outside its contract: %s", tool.name, error)
        return tool_result(
            status="internal_error",
            data=None,
            coverage_level="unavailable",
            error={
                "code": "invalid_tool_result",
                "path": error.partition(": ")[0] or "$",
                "message": error,
                "retryable": False,
            },
        )

    def _cached_read_code(self, arguments: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        for previous_args, previous_result in reversed(self._read_code_cache):
            if previous_args == arguments:
                cached = deepcopy(previous_result)
                cached["warnings"] = [
                    *cached.get("warnings", []),
                    "Reused the exact previous read_code result.",
                ]
                return cached
        requested_start = arguments.get("start_line")
        requested_end = arguments.get("end_line")
        if requested_start is None or requested_end is None:
            return None
        if int(requested_end) - int(requested_start) + 1 > int(arguments.get("max_lines", 200)):
            return None
        identity = arguments.get("symbol_id") or arguments.get("file_path")
        for previous_args, previous_result in reversed(self._read_code_cache):
            previous_identity = previous_args.get("symbol_id") or previous_args.get("file_path")
            data = previous_result.get("data")
            source = data.get("source") if isinstance(data, dict) else None
            if (
                identity != previous_identity
                or not isinstance(source, dict)
                # A truncated result carries continuation and coverage state for
                # its original request. Re-execute to derive those for this one.
                or source.get("truncated")
                or int(source.get("start_line") or 0) > int(requested_start)
                or int(source.get("end_line") or 0) < int(requested_end)
            ):
                continue
            lines = source_lines(str(source.get("code") or ""))
            start_offset = int(requested_start) - int(source["start_line"])
            end_offset = int(requested_end) - int(source["start_line"]) + 1
            if start_offset < 0 or end_offset > len(lines):
                continue
            cached = deepcopy(previous_result)
            cached_source = cached["data"]["source"]
            cached_source.update(
                {
                    "start_line": int(requested_start),
                    "end_line": int(requested_end),
                    "code": "".join(lines[start_offset:end_offset]),
                    "truncated": False,
                    "next_start_line": None,
                }
            )
            definition_end = cached_source.get("definition_end_line")
            if isinstance(definition_end, int) and int(requested_end) < definition_end:
                cached_source["truncated"] = True
                cached_source["next_start_line"] = int(requested_end) + 1
                cached["status"] = "partial"
                cached["coverage"]["level"] = "partial"
                cached["data"]["definition"]["complete"] = False
            symbol = cached["data"].get("symbol")
            if isinstance(symbol, dict):
                definition_start = symbol["location"]["start_line"]
                if int(requested_start) != definition_start:
                    cached["data"]["definition"]["complete"] = False
            cached["warnings"] = [
                *cached.get("warnings", []),
                "Reused a covered line range from a previous read_code result.",
            ]
            return cached
        return None

    @staticmethod
    def _enforce_result_limit(result: Dict[str, Any], limit: int = 60_000) -> Dict[str, Any]:
        """Fit whole records/lines, including pagination and truncation metadata."""

        def fits() -> bool:
            return len(json.dumps(result, ensure_ascii=False, default=str)) <= limit

        if fits():
            return result
        # Providers may return shared cached data; trimming owns its mutations.
        result = deepcopy(result)
        result["status"] = "partial"
        result["coverage"]["level"] = "partial"
        result.setdefault("warnings", []).append(
            f"Result was truncated at the {limit}-character tool limit."
        )

        def omitted(message: str, action: str) -> Dict[str, Any]:
            coverage = result.get("coverage") or {}
            return tool_result(
                status="partial",
                data=None,
                providers=list(coverage.get("providers") or []),
                missing=[*list(coverage.get("missing") or []), "result_size_limit"],
                coverage_details={"truncated": True, "max_result_chars": limit},
                warnings=[message],
                next_actions=[action],
            )

        def fit_prefix(values: list[Any], apply: Callable[[list[Any]], None]) -> int:
            # Binary search avoids serializing the whole payload once per removed item.
            low, high = 0, len(values)
            while low < high:
                count = (low + high + 1) // 2
                apply(values[:count])
                if fits():
                    low = count
                else:
                    high = count - 1
            apply(values[:low])
            return low

        data = result.get("data")
        if isinstance(data, dict):
            for key in ("matches", "symbols", "edges", "paths", "findings", "records"):
                values = data.get(key)
                if not isinstance(values, list) or not values:
                    continue

                def apply_items(items: list[Any]) -> None:
                    data[key] = items
                    page = result.get("page")
                    if isinstance(page, dict):
                        page.update(
                            returned=len(items),
                            has_more=True,
                            next_offset=int(page.get("offset") or 0) + len(items),
                        )

                if not fit_prefix(values, apply_items):
                    return omitted(
                        "The first result item exceeds the tool result size limit.",
                        "Narrow the query; this item cannot be retrieved by pagination.",
                    )
                break
            source = data.get("source")
            if not fits() and isinstance(source, dict) and isinstance(source.get("code"), str):
                lines = source_lines(source["code"])
                source_start = int(source.get("start_line") or 1)
                definition = data.get("definition")
                if isinstance(definition, dict):
                    definition["complete"] = False

                def apply_lines(kept: list[str]) -> None:
                    source.update(
                        code="".join(kept),
                        end_line=source_start + max(0, len(kept) - 1),
                        truncated=True,
                        next_start_line=source_start + len(kept),
                    )

                if not fit_prefix(lines, apply_lines):
                    return omitted(
                        "The first requested source line exceeds the tool result size limit.",
                        "Read a different source range; this line cannot fit in a tool result.",
                    )
            snapshot = data.get("snapshot")
            if not fits() and isinstance(snapshot, dict) and snapshot.get("data") is not None:
                snapshot["data"] = None
                result["warnings"].append(
                    "Snapshot payload was omitted at the tool result size limit."
                )
            semantics = data.get("security_semantics")
            if (
                not fits()
                and isinstance(semantics, dict)
                and isinstance(semantics.get("records"), list)
            ):
                fit_prefix(semantics["records"], lambda items: semantics.update(records=items))
            if not fits() and isinstance(data.get("contract"), dict):
                data["contract"] = {}
        return (
            result
            if fits()
            else omitted(
                f"Result payload was omitted at the {limit}-character tool limit.",
                "Retry with a smaller page or a narrower query.",
            )
        )

    def _run_post_hooks(
        self,
        tool_name: str,
        arguments: Dict[str, Any],
        result: Dict[str, Any],
        *,
        actor: str,
        enforce_policy: bool,
        start: float,
    ) -> None:
        if not enforce_policy:
            return
        self.tool_policy.run_post_hooks(
            "tool",
            tool_name,
            arguments,
            result=result,
            actor=actor,
            duration_ms=(time.perf_counter() - start) * 1000,
        )
