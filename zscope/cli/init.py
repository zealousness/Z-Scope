"""Generate a minimal Z-SCOPE configuration without embedding credentials."""

from __future__ import annotations

from pathlib import Path

import click

TEMPLATE = """# Generated by zscope-init. Keep API keys in environment variables.
llms:
  default:
    provider: openai_compatible
    base_url: ${Z_SCOPE_LLM_BASE_URL}
    models: [${Z_SCOPE_LLM_MODEL}]
    api_key: ${Z_SCOPE_API_KEY}

project:
  root: .
  source_root: .
  language: {language}
  agents:
    - name: semantic_modeler
      llm_ref: default
    - name: vulnerability_analyzer
      llm_ref: default
    - name: validator_agent
      llm_ref: default

indexing:
  backend: auto
  java:
    structure: [sootup, wala]
    signals: [joern]

rules:
  packs: []
  providers: []
  disabled_ids: []

analysis:
  snapshot_dir: .zscope_snapshots
"""


@click.command()
@click.option(
    "--language", type=click.Choice(["auto", "c_cpp", "java"]), default="auto", show_default=True
)
@click.option(
    "--output",
    type=click.Path(dir_okay=False, path_type=Path),
    default=Path("zscope.yaml"),
    show_default=True,
)
@click.option("--force", is_flag=True, help="Replace an existing generated configuration.")
def main(language: str, output: Path, force: bool) -> None:
    """Create a minimal, explicit project configuration."""

    destination = output.expanduser()
    if destination.exists() and not force:
        raise click.ClickException(f"refusing to overwrite existing file: {destination}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(TEMPLATE.format(language=language), encoding="utf-8")
    click.echo(f"Created {destination}")


if __name__ == "__main__":
    main()
