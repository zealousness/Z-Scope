"""Capture actual development inputs, including uncommitted source, without Git mutation."""

from __future__ import annotations

import datetime as dt
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
OUT = ROOT / ".coordination" / "20261014"
SNAPSHOT = OUT / "snapshot"
PREFIXES = ("zscope/", "tests/", "scripts/", "native/", "requirements/", "test/range/")
DOCS = (
    "docs/architecture.md", "docs/range-benchmark.md", "docs/rule-development.md",
    "docs/modules/", "docs/Z-Scope_Agent_Implementation_Plan/zscope-agent-implementation-plan/",
)
SUFFIXES = {".py", ".c", ".cc", ".cpp", ".h", ".hpp", ".md", ".yaml", ".yml", ".json", ".toml", ".txt", ".cjs", ".js", ".css", ".html", ".sh", ".cmake", ".xml"}
BRANCHES = ("s08-owner", "u02-projection", "u02-disposition", "s09-prep", "s07-oracle", "s01-instances", "doc-audit")


def git(*args: str) -> str:
    return subprocess.check_output(["git", *args], cwd=ROOT).decode("utf-8", errors="strict")


def main() -> None:
    if (HERE / "baseline.json").exists() or SNAPSHOT.exists():
        raise SystemExit("baseline already exists; refuse to overwrite")
    paths = set(git("ls-files", "-z", "--cached", "--others", "--exclude-standard").split("\0"))
    rows = []
    for name in sorted(paths):
        if not name or "/coordination/" in name or "__pycache__" in name:
            continue
        path = ROOT / name
        if not path.is_file():
            continue
        if not (name.startswith(PREFIXES) or name.startswith(DOCS) or "/" not in name):
            continue
        if path.suffix not in SUFFIXES and path.name not in {"CMakeLists.txt", "Makefile", ".gitignore"}:
            continue
        if any(word in path.name.lower() for word in ("local.env", "credential", "secret", ".pem")):
            continue
        raw = path.read_bytes()
        if len(raw) > 16 * 1024 * 1024:
            raise RuntimeError(f"development input too large: {name}")
        target = SNAPSHOT / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(raw)
        digest = hashlib.sha256(raw).hexdigest()
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise RuntimeError(f"concurrent input change while capturing: {name}; preserve partial snapshot")
        rows.append({"path": name, "sha256": digest, "size": len(raw)})
    canonical = json.dumps(rows, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode()
    value = {
        "schema": "zscope.coordination-source-baseline.v1",
        "captured_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "root": str(ROOT), "git_head_reference_only": git("rev-parse", "HEAD").strip(),
        "git_branch": git("branch", "--show-current").strip(),
        "working_tree_status": git("status", "--short"),
        "snapshot": str(SNAPSHOT), "source_manifest_sha256": hashlib.sha256(canonical).hexdigest(),
        "file_count": len(rows), "files": rows,
        "exclusions": ["Git internals", "generated bytecode", "historical evidence/benchmarks", "local credentials/config", "coordination outputs"],
    }
    (HERE / "baseline.json").write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    # All branches inherit the same captured dirty source bytes, not HEAD.
    for branch in BRANCHES:
        workspace = OUT / "workspaces" / branch
        if workspace.exists():
            raise RuntimeError(f"branch already exists: {workspace}")
        shutil.copytree(SNAPSHOT, workspace)
        target = workspace / "docs" / "Z-Scope_Agent_Implementation_Plan" / "zscope-agent-implementation-plan" / "coordination" / "2026-10-14"
        target.mkdir(parents=True)
        shutil.copyfile(HERE / "API_CONTRACT.md", target / "API_CONTRACT.md")
        (workspace / "COORDINATION_BASELINE.json").write_text(json.dumps({"manifest_sha256": value["source_manifest_sha256"], "branch": branch}) + "\n", encoding="utf-8")
    print(json.dumps({"file_count": len(rows), "source_manifest_sha256": value["source_manifest_sha256"], "snapshot": str(SNAPSHOT), "branches": list(BRANCHES)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
