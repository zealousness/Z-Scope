"""Runtime adapter for policy-controlled execution of registered tools."""

import logging
import time
from typing import Any, Dict, Iterable, List, Optional, TYPE_CHECKING

from ..framework.base import BaseTool
from ..snapshots.store import SnapshotStore
from .policy import ToolPolicy
from .registry import build_tool_registry

if TYPE_CHECKING:
    from ..config.user_config_store import UserConfigStore
    from ..retrieval.code_index import CodeIndex

logger = logging.getLogger(__name__)


class ToolsRuntime:
    """Expose registered tools through one policy and execution pipeline."""

    def __init__(
        self,
        code_index: "CodeIndex",
        snapshot_store: SnapshotStore,
        user_config: Optional["UserConfigStore"] = None,
        tool_policy: Optional[ToolPolicy] = None,
        *,
        tools: Optional[Iterable[BaseTool]] = None,
    ) -> None:
        self.code_index = code_index
        self.snapshot_store = snapshot_store
        self.user_config = user_config
        self.tool_policy = tool_policy or ToolPolicy.allow_all()
        registry = (
            build_tool_registry(code_index, snapshot_store, user_config)
            if tools is None
            else self._registry_from_tools(tools)
        )
        self._tools_by_name = registry
        self._location_context: Dict[str, Any] = {
            "file_path": None,
            "line": None,
            "start_line": None,
            "end_line": None,
        }
        self._negative_tool_cache: Dict[tuple[str, ...], Dict[str, Any]] = {}
        self._schema_cache: Optional[Dict[str, Dict[str, Any]]] = None

    @staticmethod
    def _registry_from_tools(tools: Iterable[BaseTool]) -> Dict[str, BaseTool]:
        registry: Dict[str, BaseTool] = {}
        for tool in tools:
            if tool.name in registry:
                raise ValueError(f"Duplicate tool name: {tool.name}")
            registry[tool.name] = tool
        return registry

    def _update_location_context(
        self,
        file_path: Optional[str] = None,
        line: Optional[int] = None,
        start_line: Optional[int] = None,
        end_line: Optional[int] = None,
    ) -> None:
        """Persist the latest successful location context for later tool auto-fill."""
        if file_path:
            self._location_context["file_path"] = file_path
        if line is not None:
            self._location_context["line"] = line
        if start_line is not None:
            self._location_context["start_line"] = start_line
            self._location_context["line"] = start_line
        if end_line is not None:
            self._location_context["end_line"] = end_line

    def _autofill_tool_args(self, tool_name: str, arguments: Any) -> Any:
        """Fill missing file/line arguments from recent tool context when possible."""
        if not isinstance(arguments, dict):
            return arguments
        filled = dict(arguments)
        if tool_name == "get_file_snippet":
            if not filled.get("file_path") and self._location_context.get("file_path"):
                filled["file_path"] = self._location_context["file_path"]
            if filled.get("start_line") is None:
                context_start = self._location_context.get("start_line")
                if context_start is not None:
                    filled["start_line"] = context_start
        return filled

    def get_tools_schema(self, *, apply_policy: bool = True) -> List[Dict[str, Any]]:
        """Return schemas generated by the registered tool objects."""
        schemas = [tool.get_schema() for tool in self._tools_by_name.values()]
        if apply_policy:
            return self.tool_policy.filter_tool_schemas(schemas)
        return schemas

    def _tool_schema_by_name(self) -> Dict[str, Dict[str, Any]]:
        if self._schema_cache is None:
            self._schema_cache = {
                name: tool.get_schema() for name, tool in self._tools_by_name.items()
            }
        return self._schema_cache

    def execute_tool(
        self,
        tool_name: str,
        arguments: Any,
        *,
        actor: str = "tools_runtime",
        enforce_policy: bool = True,
    ) -> Dict[str, Any]:
        """Execute a registered tool by name."""
        logger.debug("Executing tool %r with args: %s", tool_name, arguments)
        try:
            effective_args = self._autofill_tool_args(tool_name, arguments)
            tool = self._tools_by_name.get(tool_name)

            if not isinstance(effective_args, dict):
                if tool is not None:
                    validation_error = tool.validate_arguments(effective_args)
                    if validation_error:
                        return validation_error
                return {
                    "success": False,
                    "error": "Tool arguments must be a JSON object; please correct the payload and retry.",
                }

            if enforce_policy:
                policy_error = self.tool_policy.enforce_tool(
                    tool_name,
                    effective_args,
                    schema=self._tool_schema_by_name().get(tool_name),
                    actor=actor,
                )
                if policy_error:
                    return policy_error

            if tool is None:
                return {"error": f"Unknown tool: {tool_name}"}

            validation_error = tool.validate_arguments(effective_args)
            if validation_error:
                return validation_error

            start = time.perf_counter()
            cached = self._get_cached_negative_result(tool_name, effective_args)
            if cached is not None:
                self._run_post_hooks(
                    tool_name,
                    effective_args,
                    cached,
                    actor=actor,
                    enforce_policy=enforce_policy,
                    start=start,
                )
                return cached

            result = tool.execute(effective_args)
            self._cache_negative_result(tool_name, effective_args, result)
            self._update_location_from_result(tool_name, result)
            self._run_post_hooks(
                tool_name,
                effective_args,
                result,
                actor=actor,
                enforce_policy=enforce_policy,
                start=start,
            )
            return result
        except Exception as exc:
            logger.error("Tool execution error: %s", exc, exc_info=True)
            return {"error": str(exc)}

    def _get_cached_negative_result(
        self, tool_name: str, arguments: Dict[str, Any]
    ) -> Optional[Dict[str, Any]]:
        if tool_name != "get_type_info":
            return None
        cache_key = self._type_info_negative_cache_key(arguments)
        if cache_key not in self._negative_tool_cache:
            return None
        cached = dict(self._negative_tool_cache[cache_key])
        cached["cached_negative_result"] = True
        return cached

    def _cache_negative_result(
        self,
        tool_name: str,
        arguments: Dict[str, Any],
        result: Dict[str, Any],
    ) -> None:
        if tool_name == "get_type_info" and result.get("success") is False:
            cache_key = self._type_info_negative_cache_key(arguments)
            self._negative_tool_cache[cache_key] = dict(result)

    @staticmethod
    def _type_info_negative_cache_key(arguments: Dict[str, Any]) -> tuple[str, ...]:
        type_name = str(arguments.get("type_name") or "").strip()
        file_path = str(arguments.get("file_path") or "")
        file_path = file_path.replace("\\", "/").strip().lstrip("./")
        return ("get_type_info", type_name, file_path)

    def _update_location_from_result(self, tool_name: str, result: Dict[str, Any]) -> None:
        if result.get("success") is not True:
            return
        data = result.get("data")
        location: Optional[Dict[str, Any]] = None
        if tool_name in {"get_function_impl", "get_file_snippet"} and isinstance(data, dict):
            location = data
        elif tool_name == "get_function_info" and isinstance(data, dict):
            matches = data.get("matches")
            if isinstance(matches, list) and matches and isinstance(matches[0], dict):
                location = matches[0]
        if not location:
            return
        self._update_location_context(
            file_path=location.get("file_path") or location.get("file"),
            start_line=location.get("start_line"),
            end_line=location.get("end_line"),
        )

    def _run_post_hooks(
        self,
        tool_name: str,
        arguments: Dict[str, Any],
        result: Dict[str, Any],
        *,
        actor: str,
        enforce_policy: bool,
        start: float,
    ) -> None:
        if not enforce_policy:
            return
        self.tool_policy.run_post_hooks(
            "tool",
            tool_name,
            arguments,
            result=result,
            actor=actor,
            duration_ms=(time.perf_counter() - start) * 1000,
        )
