from .entry_discovery import API_PROMPT, COMM_PROMPT, INPUT_PROMPT, THREAD_PROMPT, EntryDiscovery

logger = logging.getLogger(__name__)


SOURCE_EXTENSIONS = {".c", ".cc", ".cpp", ".cxx", ".h", ".hpp", ".ph", ".inc", ".inl"}
HEADER_EXTENSIONS = {".h", ".hpp", ".ph", ".inc", ".inl"}
HUNK_RE = re.compile(
    r"^@@\s+-\d+(?:,\d+)?\s+\+(?P<start>\d+)(?:,(?P<count>\d+))?\s+@@"
)


@dataclass
class ChangedLineRange:
    """New-version line range changed by a git diff hunk."""

    file_path: str
    start_line: int
    end_line: int

    def overlaps(self, start_line: int, end_line: int) -> bool:
        return self.start_line <= end_line and self.end_line >= start_line


@dataclass
class ChangedFunction:
    """Function whose current implementation overlaps the new-version diff."""

    function_name: str
    file_path: str
    start_line: int
    end_line: int
    changed_lines: List[int] = field(default_factory=list)
    change_kind: str = "implementation"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "function_name": self.function_name,
            "file_path": self.file_path,
            "start_line": self.start_line,
            "end_line": self.end_line,
            "changed_lines": list(self.changed_lines),
            "change_kind": self.change_kind,
        }


@dataclass
class DiffImpactPlan:
    """Batch-entry payload generated from a diff."""

    component: str
    repo_root: str
    git_root: str
    source_root: str
    project_root: str
    requested_repo_root: str
    base_ref: str
    head_ref: str
    entries: List[FunctionEntry]
    changed_functions: List[ChangedFunction]
    changed_files: List[str]
    changed_headers: List[str]
    notes: List[str] = field(default_factory=list)

    def to_entry_functions_payload(self) -> Dict[str, Any]:
        return {
            "description": "Auto-generated by Z-SCOPE diff impact planning.",
            "diff_impact": {
                "component": self.component,
                "repo_root": self.repo_root,
                "git_root": self.git_root,
                "source_root": self.source_root,
                "project_root": self.project_root,
                "requested_repo_root": self.requested_repo_root,
                "base_ref": self.base_ref,
                "head_ref": self.head_ref,
                "changed_files": self.changed_files,
                "changed_headers": self.changed_headers,
                "changed_functions": [func.to_dict() for func in self.changed_functions],
                "entry_count": len(self.entries),
                "notes": self.notes,
            },
            "functions": [
                {
                    "function_name": entry.function_name,
                    "file_path": entry.file_path,
                    "custom_prompt": entry.custom_prompt,
                    "diff_focus": entry.diff_focus or {},
                }
                for entry in self.entries
            ],
        }


class DiffImpactPlanner:
    """Plan batch scan entries from git diff seeds and reverse call graph impact."""

    def __init__(
        self,
        code_index: CodeIndex,
        *,
        repo_root: Path,
        base_ref: str,
        head_ref: str = "HEAD",
        component: str = "default",
        header_files: Optional[Sequence[str]] = None,
        max_call_depth: int = 12,
        caller_limit: int = 200,
        synthetic_depth_threshold: int = 3,
    ) -> None:
        self.code_index = code_index
        self.requested_repo_root = Path(repo_root).resolve()
        self.source_root = Path(
            getattr(code_index, "source_root", None) or self.requested_repo_root
        ).resolve()
        self.project_root = Path(
            getattr(code_index, "project_root", None) or self.source_root
        ).resolve()
        self.git_root = (
            self._detect_git_root(self.requested_repo_root)
            or self._detect_git_root(self.source_root)
            or self.requested_repo_root
        )
        self.repo_root = self.git_root
        self.base_ref = base_ref
        self.head_ref = head_ref or "HEAD"
        self.component = component or "default"
        self.header_files = list(header_files or [])
        self.max_call_depth = max_call_depth
        self.caller_limit = caller_limit
        self.synthetic_depth_threshold = synthetic_depth_threshold
        self._entry_discovery = EntryDiscovery(
            code_index,
            header_files=self.header_files or None,
            project_root=self.project_root,
            source_root=self.source_root,
        )
        self._header_declarations: Optional[Dict[str, List[Dict[str, Any]]]] = None

    def plan(self) -> DiffImpactPlan:
        changed_ranges = self._collect_changed_line_ranges()
        changed_files = sorted({item.file_path for item in changed_ranges})
        changed_headers = sorted(
            file_path for file_path in changed_files if Path(file_path).suffix in HEADER_EXTENSIONS
        )
        changed_functions = self._map_changed_functions(changed_ranges)
        entries = self._build_entries(changed_functions)
        notes: List[str] = []
        if not changed_ranges:
            notes.append("No new-version source line changes were found in the requested diff.")
        if changed_ranges and not changed_functions:
            notes.append("Diff contained source changes, but no changed functions were mapped.")
            notes.extend(self._changed_function_mapping_diagnostics(changed_files))
        if not entries and changed_functions:
            notes.append("Changed functions were found, but no scan entries could be generated.")
        return DiffImpactPlan(
            component=self.component,
            repo_root=str(self.repo_root),
            git_root=str(self.git_root),
            source_root=str(self.source_root),
            project_root=str(self.project_root),
            requested_repo_root=str(self.requested_repo_root),
            base_ref=self.base_ref,
            head_ref=self.head_ref,
            entries=entries,
            changed_functions=changed_functions,
            changed_files=changed_files,
            changed_headers=changed_headers,
            notes=notes,
        )

    def write_entry_functions_file(self, path: Path, plan: DiffImpactPlan) -> Path:
        path = Path(path)
        path.write_text(
            json.dumps(plan.to_entry_functions_payload(), ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        return path

    @staticmethod
    def _detect_git_root(path: Path) -> Optional[Path]:
        try:
            proc = subprocess.run(
                ["git", "-C", str(path), "rev-parse", "--show-toplevel"],
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                check=False,
            )
        except OSError:
            return None
        if proc.returncode != 0:
            return None
        stdout = proc.stdout.strip()
        return Path(stdout).resolve() if stdout else None

    def _collect_changed_line_ranges(self) -> List[ChangedLineRange]:
        cmd = [
            "git",
            "-C",
            str(self.git_root),
            "diff",
            "--unified=0",
            "--find-renames",
            "--no-ext-diff",
            self.base_ref,
            self.head_ref,
            "--",
        ]
        try:
            proc = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                check=False,
            )
        except OSError as exc:
            raise RuntimeError(f"Failed to run git diff in {self.git_root}: {exc}") from exc
        if proc.returncode != 0:
            stderr = proc.stderr.strip() or proc.stdout.strip()
            raise RuntimeError(f"git diff failed in {self.git_root}: {stderr}")
        return self._parse_git_diff(proc.stdout)

    @staticmethod
    def _parse_git_diff(diff_text: str) -> List[ChangedLineRange]:
        ranges: List[ChangedLineRange] = []
        current_file = ""
        for raw_line in diff_text.splitlines():
            line = raw_line.rstrip("\n")
            if line.startswith("+++ "):
                marker = line[4:].strip()
                if marker == "/dev/null":
                    current_file = ""
                elif marker.startswith("b/"):
                    current_file = marker[2:]
                else:
                    current_file = marker
                continue
            match = HUNK_RE.match(line)
            if not match or not current_file:
                continue
            count = int(match.group("count") or "1")
            if count <= 0:
                continue
            start = int(match.group("start"))
            ranges.append(
                ChangedLineRange(
                    file_path=current_file,
                    start_line=start,
                    end_line=start + count - 1,
                )
            )
        return ranges

    def _map_changed_functions(
        self,
        changed_ranges: Sequence[ChangedLineRange],
    ) -> List[ChangedFunction]:
        ranges_by_file: Dict[str, List[ChangedLineRange]] = {}
        for item in changed_ranges:
            if Path(item.file_path).suffix not in SOURCE_EXTENSIONS:
                continue
            for key in self._diff_file_abs_keys(item.file_path):
                ranges_by_file.setdefault(key, []).append(item)

        by_key: Dict[Tuple[str, str], ChangedFunction] = {}
        for name, info in self._iter_indexed_functions():
            indexed_file = str(info.get("file") or "")
            start_line = int(info.get("start_line") or 0)
            end_line = int(info.get("end_line") or 0)
            if not indexed_file or start_line <= 0 or end_line <= 0:
                continue
            resolved_file = self._resolve_indexed_file(indexed_file)
            file_ranges = ranges_by_file.get(self._abs_key(resolved_file))
            if not file_ranges:
                continue
            changed_lines: List[int] = []
            for item in file_ranges:
                if item.overlaps(start_line, end_line):
                    changed_lines.extend(
                        line_no
                        for line_no in range(item.start_line, item.end_line + 1)
                        if start_line <= line_no <= end_line
                    )
            if not changed_lines:
                continue
            rel_file = self._normalize_file(resolved_file)
            by_key[(name, rel_file)] = ChangedFunction(
                function_name=name,
                file_path=rel_file,
                start_line=start_line,
                end_line=end_line,
                changed_lines=sorted(set(changed_lines)),
            )

        for header_change in self._map_changed_header_declarations(changed_ranges):
            key = (header_change.function_name, header_change.file_path)
            by_key.setdefault(key, header_change)

        return sorted(by_key.values(), key=lambda item: (item.file_path, item.start_line, item.function_name))

    def _map_changed_header_declarations(
        self,
        changed_ranges: Sequence[ChangedLineRange],
    ) -> Iterable[ChangedFunction]:
        ranges_by_file: Dict[str, List[ChangedLineRange]] = {}
        for item in changed_ranges:
            if Path(item.file_path).suffix in HEADER_EXTENSIONS:
                for key in self._diff_file_abs_keys(item.file_path):
                    ranges_by_file.setdefault(key, []).append(item)

        if not ranges_by_file:
            return []

        changed: List[ChangedFunction] = []
        for name, declarations in self._header_declaration_map().items():
            for decl in declarations:
                decl_file = str(decl.get("filename") or "")
                decl_line = int(decl.get("lineNumber") or 0)
                if not decl_file or decl_line <= 0:
                    continue
                resolved = self._resolve_candidate_file(decl_file)
                file_ranges = ranges_by_file.get(self._abs_key(resolved))
                if not file_ranges or not any(item.overlaps(decl_line, decl_line) for item in file_ranges):
                    continue
                impl = self._get_impl(name)
                if not impl:
                    continue
                changed.append(
                    ChangedFunction(
                        function_name=name,
                        file_path=str(impl.get("file") or self._normalize_file(resolved)),
                        start_line=int(impl.get("start_line") or decl_line),
                        end_line=int(impl.get("end_line") or decl_line),
                        changed_lines=[decl_line],
                        change_kind="header_declaration",
                    )
                )
        return changed

    def _build_entries(self, changed_functions: Sequence[ChangedFunction]) -> List[FunctionEntry]:
        entries_by_key: Dict[Tuple[str, str, str], Dict[str, Any]] = {}
        for changed in changed_functions:
            external_paths = self._find_external_entry_paths(changed)
            needs_synthetic = not external_paths
            for candidate, path in external_paths:
                self._merge_entry(entries_by_key, candidate, changed, path, fallback_reason="")
                if len(path) - 1 > self.synthetic_depth_threshold:
                    needs_synthetic = True
            if needs_synthetic:
                synthetic = self._synthetic_candidate(changed)
                reason = "no_external_entry_found" if not external_paths else "deep_path_exceeds_model_depth"
                self._merge_entry(
                    entries_by_key,
                    synthetic,
                    changed,
                    [changed.function_name],
                    fallback_reason=reason,
                )

        entries: List[FunctionEntry] = []
        for item in sorted(entries_by_key.values(), key=lambda value: value["sort_key"]):
            focus = item["focus"]
            focus["changed_functions"] = sorted(
                focus["changed_functions"],
                key=lambda value: (value.get("file_path", ""), value.get("function_name", "")),
            )
            focus["affected_paths"] = sorted(
                focus["affected_paths"],
                key=lambda value: (
                    value.get("changed_function", ""),
                    len(value.get("path") or []),
                    "/".join(value.get("path") or []),
                ),
            )
            entries.append(
                FunctionEntry(
                    function_name=item["function_name"],
                    file_path=item["file_path"],
                    custom_prompt=self._custom_prompt(item["base_prompt"], focus),
                    diff_focus=focus,
                )
            )
        return entries

    def _find_external_entry_paths(
        self,
        changed: ChangedFunction,
    ) -> List[Tuple[Dict[str, Any], List[str]]]:
        results: List[Tuple[Dict[str, Any], List[str]]] = []
        queue: List[Tuple[str, List[str], int]] = [(changed.function_name, [changed.function_name], 0)]
        visited = {changed.function_name}
        while queue:
            current, changed_to_current_path, depth = queue.pop(0)
            candidate = self._classify_external_entry(current)
            if candidate:
                results.append((candidate, list(reversed(changed_to_current_path))))
            if depth >= self.max_call_depth:
                continue
            for caller in self._get_callers(current):
                caller_name = str(caller.get("name") or "")
                if not caller_name or caller_name in visited:
                    continue
                thread_candidate = self._thread_entry_candidate(current, caller_name)
                if thread_candidate:
                    results.append((thread_candidate, list(reversed(changed_to_current_path))))
                visited.add(caller_name)
                queue.append((caller_name, changed_to_current_path + [caller_name], depth + 1))
        return results

    def _thread_entry_candidate(self, target_name: str, creator_name: str) -> Optional[Dict[str, Any]]:
        creator_impl = self._get_impl(creator_name)
        if not creator_impl:
            return None
        code = str(creator_impl.get("code") or "")
        stripped = EntryDiscovery._strip_code_for_call_search(code)
        thread_hits = EntryDiscovery._find_calls(
            stripped,
            self._entry_discovery.thread_calls,
            code_is_stripped=True,
        )
        if not thread_hits:
            return None
        for target, call in EntryDiscovery._find_thread_entry_targets(
            stripped,
            thread_hits,
            code_is_stripped=True,
        ):
            if target != target_name:
                continue
            target_impl = self._get_impl(target_name)
            if not target_impl:
                return None
            return {
                "function_name": target_name,
                "file_path": str(target_impl.get("file") or ""),
                "exposure": "thread",
                "reasons": [f"thread_entry:{call}", f"thread_creator:{creator_name}"],
                "base_prompt": THREAD_PROMPT,
                "confidence": 0.88,
            }
        return None

    def _classify_external_entry(self, func_name: str) -> Optional[Dict[str, Any]]:
        impl = self._get_impl(func_name)
        if not impl:
            return None
        code = str(impl.get("code") or "")
        stripped = EntryDiscovery._strip_code_for_call_search(code)
        exposure_parts: List[str] = []
        reasons: List[str] = []
        prompts: List[str] = []
        confidence = 0.5
        declaration = self._first_header_declaration(func_name)
        if declaration:
            exposure_parts.append("api")
            reasons.append("declared_in_header")
            prompts.append(API_PROMPT)
            confidence = max(confidence, 0.9)

        comm_hits = EntryDiscovery._find_calls(
            stripped,
            self._entry_discovery.communication_calls,
            code_is_stripped=True,
        )
        shm_hits = EntryDiscovery._find_calls(
            stripped,
            self._entry_discovery.shared_memory_calls,
            code_is_stripped=True,
        )
        if comm_hits or shm_hits:
            exposure_parts.append("communication")
            reasons.extend([f"calls:{hit}" for hit in comm_hits])
            reasons.extend([f"shared_memory:{hit}" for hit in shm_hits])
            prompts.append(COMM_PROMPT)
            confidence = max(confidence, 0.85)

        input_hits = EntryDiscovery._find_calls(
            stripped,
            self._entry_discovery.input_calls,
            code_is_stripped=True,
        )
        if input_hits and not exposure_parts:
            exposure_parts.append("other_user_input")
            reasons.extend([f"input:{hit}" for hit in input_hits])
            prompts.append(INPUT_PROMPT)
            confidence = max(confidence, 0.7)

        if not exposure_parts:
            return None
        impl_file = str(impl.get("file") or "")
        return {
            "function_name": func_name,
            "file_path": impl_file,
            "exposure": "+".join(dict.fromkeys(exposure_parts)),
            "reasons": sorted(set(reasons)),
            "base_prompt": " ".join(prompts),
            "confidence": confidence,
        }

    def _synthetic_candidate(self, changed: ChangedFunction) -> Dict[str, Any]:
        return {
            "function_name": changed.function_name,
            "file_path": changed.file_path,
            "exposure": "synthetic_internal_diff_entry",
            "reasons": ["diff_changed_function"],
            "base_prompt": (
                "Synthetic internal diff entry. This function was changed by the requested diff, "
                "but no external entry was proven within the configured caller search budget. "
                "Analyze the changed behavior and explicitly verify whether an external caller, "
                "callback, dispatcher, or exported API can reach it before treating a finding as exploitable."
            ),
            "confidence": 0.5,
        }

    def _merge_entry(
        self,
        entries_by_key: Dict[Tuple[str, str, str], Dict[str, Any]],
        candidate: Dict[str, Any],
        changed: ChangedFunction,
        path: List[str],
        *,
        fallback_reason: str,
    ) -> None:
        function_name = str(candidate.get("function_name") or changed.function_name)
        file_path = str(candidate.get("file_path") or changed.file_path)
        key = (self.component, function_name, file_path)
        item = entries_by_key.get(key)
        if item is None:
            focus = {
                "mode": "diff_impact",
                "component": self.component,
                "repo_root": str(self.repo_root),
                "git_root": str(self.git_root),
                "source_root": str(self.source_root),
                "project_root": str(self.project_root),
                "requested_repo_root": str(self.requested_repo_root),
                "base_ref": self.base_ref,
                "head_ref": self.head_ref,
                "entry_function": function_name,
                "entry_file_path": file_path,
                "entry_exposure": candidate.get("exposure", ""),
                "entry_reasons": list(candidate.get("reasons") or []),
                "fallback_reasons": [],
                "changed_functions": [],
                "affected_paths": [],
            }
            item = {
                "function_name": function_name,
                "file_path": file_path,
                "base_prompt": str(candidate.get("base_prompt") or ""),
                "focus": focus,
                "changed_keys": set(),
                "path_keys": set(),
                "sort_key": (0 if not fallback_reason else 1, function_name, file_path),
            }
            entries_by_key[key] = item

        focus = item["focus"]
        changed_key = (changed.function_name, changed.file_path)
        if changed_key not in item["changed_keys"]:
            focus["changed_functions"].append(changed.to_dict())
            item["changed_keys"].add(changed_key)
        path_key = (changed.function_name, tuple(path))
        if path_key not in item["path_keys"]:
            focus["affected_paths"].append(
                {
                    "entry_function": function_name,
                    "changed_function": changed.function_name,
                    "path": path,
                    "depth": max(0, len(path) - 1),
                }
            )
            item["path_keys"].add(path_key)
        if fallback_reason and fallback_reason not in focus["fallback_reasons"]:
            focus["fallback_reasons"].append(fallback_reason)

    def _custom_prompt(self, base_prompt: str, focus: Dict[str, Any]) -> str:
        changed_names = ", ".join(
            item.get("function_name", "") for item in focus.get("changed_functions", [])[:12]
        )
        path_count = len(focus.get("affected_paths") or [])
        fallback = ", ".join(focus.get("fallback_reasons") or [])
        diff_prompt = (
            "Diff impact scan. The entry was selected from git diff impact analysis, not full-project "
            "entry discovery. You must inspect the supplied diff_focus changed_functions and "
            "entry-to-change affected_paths before concluding. Keep all findings, but distinguish "
            "incremental, existing, or unknown diff relevance in the reasoning when possible. "
            f"Changed functions: {changed_names or 'none'}. Affected path count: {path_count}."
        )
        if fallback:
            diff_prompt += f" Fallback reason: {fallback}."
        return " ".join(part for part in [base_prompt, diff_prompt] if part)

    def _iter_indexed_functions(self) -> Iterable[Tuple[str, Dict[str, Any]]]:
        if hasattr(self.code_index, "ensure_index_ready"):
            self.code_index.ensure_index_ready()
        index = getattr(self.code_index, "_function_index", None)
        if isinstance(index, dict):
            for name, info in index.items():
                if isinstance(info, dict):
                    yield str(name), dict(info)
            return
        for name in self.code_index.list_functions(limit=100000):
            impl = self._get_impl(name)
            if impl:
                yield name, {
                    "file": impl.get("file"),
                    "start_line": impl.get("start_line"),
                    "end_line": impl.get("end_line"),
                }

    def _get_impl(self, func_name: str) -> Optional[Dict[str, Any]]:
        try:
            return self.code_index.get_function_impl(
                func_name,
                include_context=False,
                warn_missing=False,
            )
        except TypeError:
            try:
                return self.code_index.get_function_impl(func_name, warn_missing=False)
            except TypeError:
                return self.code_index.get_function_impl(func_name)

    def _get_callers(self, func_name: str) -> List[Dict[str, Any]]:
        try:
            callers = self.code_index.get_callers(func_name, limit=self.caller_limit)
        except Exception as exc:
            logger.debug("Failed to get callers for %s: %s", func_name, exc)
            callers = []
        return [caller for caller in callers if isinstance(caller, dict)]

    def _header_declaration_map(self) -> Dict[str, List[Dict[str, Any]]]:
        if self._header_declarations is not None:
            return self._header_declarations
        declarations: Dict[str, List[Dict[str, Any]]] = {}
        try:
            raw_decls = self.code_index.get_header_declared_functions(None)
        except Exception:
            raw_decls = []
        for item in raw_decls:
            if not isinstance(item, dict):
                continue
            name = str(item.get("name") or "")
            filename = str(item.get("filename") or "")
            if not name or (self.header_files and not matches_configured_path(filename, self.header_files)):
                continue
            declarations.setdefault(name, []).append(dict(item))
        self._header_declarations = declarations
        return declarations

    def _first_header_declaration(self, func_name: str) -> Optional[Dict[str, Any]]:
        declarations = self._header_declaration_map().get(func_name) or []
        return declarations[0] if declarations else None

    def _resolve_indexed_file(self, file_path: str) -> Path:
        resolved = self._resolve_existing_candidate_file(file_path)
        if resolved:
            return resolved
        resolver = getattr(self.code_index, "_resolve_file_path", None)
        if callable(resolver):
            resolved = Path(resolver(file_path)).resolve()
            if resolved.exists():
                return resolved
        return self._resolve_candidate_file(file_path)

    def _resolve_candidate_file(self, file_path: str) -> Path:
        resolved = self._resolve_existing_candidate_file(file_path)
        if resolved:
            return resolved
        candidates = self._candidate_files(file_path)
        if candidates:
            return candidates[0]
        return (self.repo_root / file_path).resolve()

    def _resolve_existing_candidate_file(self, file_path: str) -> Optional[Path]:
        for candidate in self._candidate_files(file_path):
            if candidate.exists():
                return candidate
        return None

    def _candidate_files(self, file_path: str) -> List[Path]:
        path = Path(file_path)
        if path.is_absolute():
            return [path.resolve()]

        candidates: List[Path] = []
        seen: set[str] = set()
        for base in self._path_roots():
            candidate = (base / path).resolve()
            key = self._abs_key(candidate)
            if key in seen:
                continue
            candidates.append(candidate)
            seen.add(key)
        return candidates

    def _diff_file_abs_keys(self, file_path: str) -> List[str]:
        keys: List[str] = []
        seen: set[str] = set()
        for candidate in self._candidate_files(file_path):
            if not candidate.exists():
                continue
            key = self._abs_key(candidate)
            if key in seen:
                continue
            keys.append(key)
            seen.add(key)
        return keys

    def _path_roots(self) -> List[Path]:
        roots: List[Path] = []
        seen: set[str] = set()
        source_parent = self.source_root.parent if self.source_root else None
        for base in (
            self.git_root,
            self.source_root,
            self.project_root,
            source_parent,
            self.requested_repo_root,
        ):
            if base is None:
                continue
            root = Path(base).resolve()
            key = self._abs_key(root)
            if key in seen:
                continue
            roots.append(root)
            seen.add(key)
        return roots

    def _changed_function_mapping_diagnostics(self, changed_files: Sequence[str]) -> List[str]:
        notes = [
            "Diff path diagnostics: "
            f"git_root={self.git_root}, "
            f"source_root={self.source_root}, "
            f"project_root={self.project_root}, "
            f"requested_repo_root={self.requested_repo_root}."
        ]

        path_notes: List[str] = []
        for file_path in list(changed_files)[:5]:
            candidates = [
                f"{candidate} exists={str(candidate.exists()).lower()}"
                for candidate in self._candidate_files(file_path)[:5]
            ]
            path_notes.append(f"{file_path} -> [{'; '.join(candidates) or 'no candidates'}]")
        if path_notes:
            notes.append("Changed file candidate paths: " + " | ".join(path_notes))

        samples = self._indexed_function_file_samples(limit=8)
        if samples:
            notes.append("Indexed function file samples: " + ", ".join(samples))
        else:
            notes.append("Indexed function file samples: none.")
        return notes

    def _indexed_function_file_samples(self, limit: int = 8) -> List[str]:
        samples: List[str] = []
        seen: set[str] = set()
        for _name, info in self._iter_indexed_functions():
            file_path = str(info.get("file") or "")
            if not file_path or file_path in seen:
                continue
            samples.append(file_path)
            seen.add(file_path)
            if len(samples) >= limit:
                break
        return samples

    def _normalize_file(self, file_path: Path) -> str:
        try:
            return normalize_path(file_path, self.source_root).replace("\\", "/")
        except Exception:
            pass
        try:
            return normalize_path(file_path, self.project_root).replace("\\", "/")
        except Exception:
            pass
        return normalize_path(file_path, self.repo_root).replace("\\", "/")

    @staticmethod
    def _abs_key(path: Path) -> str:
        resolved = Path(path).resolve()
        value = str(resolved)
        return value.lower() if os.name == "nt" else value
