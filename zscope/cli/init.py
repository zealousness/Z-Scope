"""Generate a strict, language-aware Z-SCOPE configuration v3.

The YAML file is placed directly in the project directory, which is the only
root for project-relative paths. Public root/source_root keys are forbidden.
Credentials stay in environment references. Only wired fields are emitted.

Every user-controlled string (root, target id, compile database path) is
serialized through :func:`_yaml_scalar` — a real JSON encoder, whose output
is a YAML 1.2 double-quoted scalar — so characters that change YAML meaning
(``#``, ``: ``, quotes, newlines) survive a round trip through the strict v3
parser instead of being spliced into the document verbatim.
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path
from typing import Optional

import click
import yaml

from ..config.config import detect_project_language
from ..config.v2 import SCAN_DEPTHS_BY_LANGUAGE
from ..config.v3 import PRESET_DEPTH_MAPPING, SCAN_PRESETS, parse_user_config_v3_document
from ..config.project_semantics import render_empty_project_semantics


def _yaml_scalar(value: str) -> str:
    """Serialize one user-controlled string as a single-line YAML scalar.

    JSON string syntax is a subset of YAML 1.2 double-quoted scalars, and the
    encoder escapes ``#``, ``: ``, quotes, backslashes, and newlines without
    any hand-written quoting rules.  The strict parser therefore reads the
    document back to the exact same string.
    """

    return json.dumps(value, ensure_ascii=False)


def _compile_commands(project_root: Path) -> str:
    candidates = (
        project_root / "build" / "compile_commands.json",
        project_root / "compile_commands.json",
        # External projects commonly keep benchmark or CI builds in a named
        # sibling build directory.  zscope-init must bind an existing database
        # when the conventional benchmark layout is present; emitting the
        # nonexistent build/ fallback makes the very next prepare/discovery
        # command fail even though a current database is available.
        project_root / "build-rwb" / "compile_commands.json",
    )
    for candidate in candidates:
        if candidate.is_file():
            return candidate.relative_to(project_root).as_posix()
    return "build/compile_commands.json"


def _default_preset(language: str) -> str:
    # Preserve the existing C/C++ default execution depth; Java supports fast only.
    return "deep" if language == "c_cpp" else "fast"


def _preset_allowed(preset: str, language: str) -> bool:
    depth = PRESET_DEPTH_MAPPING[preset]
    return depth in SCAN_DEPTHS_BY_LANGUAGE.get(language, frozenset())


def _render(
    *,
    language: str,
    project_root: Path,
    config_dir: Path,
    target_id: str,
    compile_commands: str,
    preset: str,
) -> str:
    if project_root.resolve() != config_dir.resolve():
        raise ValueError("configuration must be stored directly in the project directory")
    lines = [
        "# Generated by zscope-init. Keep API keys in environment variables.",
        "config_version: 3",
        "",
        "llms:",
        "  default:",
        '    base_urls: ["${Z_SCOPE_LLM_BASE_URL}"]',
        '    models: ["${Z_SCOPE_LLM_MODEL}"]',
        '    api_key: "${Z_SCOPE_API_KEY}"',
        "    max_tokens: 8192 # 单次响应上限；扫描总用量由报告计量。",
        "",
        "project:",
        f"  language: {language}",
        "  # 本 YAML 所在目录是唯一工程根；项目相对路径均基于该目录。",
        "  platform: linux_user",
        "  targets:",
        f"    - id: {_yaml_scalar(target_id)}",
    ]
    if language == "c_cpp":
        lines.insert(lines.index("  targets:"), "  semantics_file: zscope.semantics.yaml")
        lines.append(
            f"      compile_commands: {_yaml_scalar(compile_commands)} # 相对本 YAML 所在目录"
        )
    lines.extend(
        [
            "",
            "scan:",
            f"  preset: {preset} # fast=快速；balanced=均衡；deep=深度，不启用实验。",
        ]
    )
    if language == "java":
        lines.append("  # Java 当前仅开放 fast；balanced/deep 尚未通过该语言门禁。")
    lines.extend(
        [
            "  # focus/reproduction 已校验保留但尚未消费；execution 时窗与并发预算见",
            "  # 仓库根目录 zscope.c_cpp.yaml / zscope.java.yaml 模板注释。",
        ]
    )
    return "\n".join(lines) + "\n"


def render_project_config(
    project_root: Path,
    *,
    language: str,
    target_id: str = "main",
    compile_commands: Optional[str] = None,
    preset: Optional[str] = None,
) -> str:
    """Render a rootless v3 document for direct placement in project_root."""
    root = Path(project_root).resolve()
    if not root.is_dir():
        raise ValueError(f"project directory does not exist: {root}")
    if language not in {"c_cpp", "java"}:
        raise ValueError("language must be c_cpp or java")
    selected_preset = _default_preset(language) if preset is None else preset
    if selected_preset not in SCAN_PRESETS or not _preset_allowed(selected_preset, language):
        raise ValueError(f"unsupported preset for {language}: {selected_preset}")
    if language == "java" and compile_commands is not None:
        raise ValueError("compile_commands is not valid for Java")
    rendered = _render(
        language=language,
        project_root=root,
        config_dir=root,
        target_id=target_id,
        compile_commands=_compile_commands(root) if compile_commands is None else compile_commands,
        preset=selected_preset,
    )
    # Validate shape without resolving credential environment references or
    # composing execution. This is the same public parser used by Web editing.
    parse_user_config_v3_document(root / "zscope.yaml", yaml.safe_load(rendered))
    return rendered


@click.command()
@click.option(
    "--language", type=click.Choice(["auto", "c_cpp", "java"]), default="auto", show_default=True
)
@click.option(
    "--project-root",
    type=click.Path(file_okay=False, path_type=Path),
    default=Path("."),
    show_default=True,
)
@click.option(
    "--output",
    type=click.Path(dir_okay=False, path_type=Path),
    default=None,
    help="Config filename inside --project-root (default: PROJECT/zscope.yaml).",
)
@click.option(
    "--preset",
    type=click.Choice(list(SCAN_PRESETS)),
    default=None,
    help="Quality tier (default: deep for c_cpp, fast for java).",
)
@click.option(
    "--target-id",
    default="main",
    show_default=True,
    help="Identity of the single generated build target.",
)
@click.option(
    "--interactive/--no-interactive",
    default=None,
    help="Confirm detected language, target, and preset (auto-detected for TTY).",
)
@click.option("--force", is_flag=True, help="Replace an existing generated configuration.")
def main(
    language: str,
    project_root: Path,
    output: Optional[Path],
    preset: Optional[str],
    target_id: str,
    interactive: Optional[bool],
    force: bool,
) -> None:
    """Create a strict, explicit project configuration v3."""

    root = project_root.expanduser().resolve()
    if not root.is_dir():
        raise click.ClickException(f"project root is not a directory: {root}")
    use_interactive = sys.stdin.isatty() if interactive is None else interactive
    detected = detect_project_language(root) if language == "auto" else language
    if use_interactive:
        detected = click.prompt(
            "Project language",
            type=click.Choice(["c_cpp", "java"]),
            default=detected,
        )

    target_id = target_id.strip() or "main"
    if use_interactive:
        target_id = click.prompt("Target id", default=target_id).strip() or "main"
    compile_commands = _compile_commands(root)
    if detected == "c_cpp" and use_interactive:
        compile_commands = click.prompt(
            "compile_commands (relative to project root)", default=compile_commands
        )

    chosen_preset = preset or _default_preset(detected)
    if use_interactive:
        allowed = [item for item in SCAN_PRESETS if _preset_allowed(item, detected)]
        default_preset = chosen_preset if chosen_preset in allowed else allowed[0]
        chosen_preset = click.prompt(
            "Scan preset",
            type=click.Choice(allowed),
            default=default_preset,
        )
    if not _preset_allowed(chosen_preset, detected):
        raise click.ClickException(
            f"scan preset {chosen_preset!r} is not currently available for "
            f"language={detected!r}; use {_default_preset(detected)!r}"
        )

    destination = output.expanduser().resolve() if output is not None else root / "zscope.yaml"
    if destination.parent != root:
        raise click.ClickException(
            "--output must be directly inside --project-root; the YAML directory is the only project root"
        )
    semantics_destination = root / "zscope.semantics.yaml" if detected == "c_cpp" else None
    existing_targets = [
        path for path in (destination, semantics_destination) if path is not None and path.exists()
    ]
    if existing_targets and not force:
        raise click.ClickException(
            "refusing to overwrite existing file(s): "
            + ", ".join(str(path) for path in existing_targets)
        )
    destination.parent.mkdir(parents=True, exist_ok=True)
    rendered = _render(
        language=detected,
        project_root=root,
        config_dir=destination.parent,
        target_id=target_id,
        compile_commands=compile_commands,
        preset=chosen_preset,
    )
    payloads = [(destination, rendered)]
    if semantics_destination is not None:
        payloads.append((semantics_destination, render_empty_project_semantics()))
    temporary: list[tuple[Path, Path]] = []
    published: list[Path] = []
    try:
        for target, payload in payloads:
            descriptor, raw_temp = tempfile.mkstemp(
                prefix=f".{target.name}.", suffix=".tmp", dir=str(target.parent)
            )
            temp = Path(raw_temp)
            with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(payload)
                handle.flush()
                os.fsync(handle.fileno())
            temporary.append((temp, target))
        for temp, target in temporary:
            if force:
                os.replace(temp, target)
            else:
                os.link(temp, target)
                temp.unlink()
            published.append(target)
    except Exception:
        # With the default non-overwrite contract every published path was
        # absent on entry, so rollback prevents a half-created config pair.
        # ``--force`` retains the historical overwrite behavior because an
        # old file must never be deleted as an attempted rollback.
        if not force:
            for target in reversed(published):
                try:
                    target.unlink()
                except FileNotFoundError:
                    pass
        raise
    finally:
        for temp, _target in temporary:
            if temp.exists():
                temp.unlink()
    click.echo(
        f"Created config v3: {destination} "
        f"(language={detected}, preset={chosen_preset}, target={target_id})"
    )
    if semantics_destination is not None:
        click.echo(f"Created project semantics: {semantics_destination}")
    click.echo(
        "Multi-target documents can be saved and prepared, but the current "
        "execution chain starts exactly one declared target."
    )
    click.echo(
        "Next: declare known primitives in zscope.semantics.yaml, run "
        "zscope --discover-primitives, review pending rows, then run "
        "zscope-config validate and zscope-config prepare."
    )


if __name__ == "__main__":
    main()
