def _method_bounds(lines: list[str], function: str) -> tuple[int, int]:
    if function.startswith("<project-file>") or function in {"orderByVul", "likeVul", "inVul"}:
        return 1, len(lines)
    pattern = re.compile(r"\b" + re.escape(function) + r"\s*\(")
    start_index = next((i for i, line in enumerate(lines) if pattern.search(line)), None)
    if start_index is None:
        return 1, len(lines)
    brace_depth = 0
    seen_open = False
    for i in range(start_index, len(lines)):
        brace_depth += lines[i].count("{")
        if "{" in lines[i]:
            seen_open = True
        brace_depth -= lines[i].count("}")
        if seen_open and brace_depth <= 0:
            return start_index + 1, i + 1
    return start_index + 1, len(lines)


def _find_line(lines: list[str], function: str, line_hint: str) -> int:
    start, end = _method_bounds(lines, function)
    search_ranges = [(start, end), (1, len(lines))]
    for range_start, range_end in search_ranges:
        for lineno in range(range_start, range_end + 1):
            if line_hint in lines[lineno - 1]:
                return lineno
    raise ValueError(f"line hint not found for {function}: {line_hint!r}")


def _validate_seed(project_root: Path, item: dict[str, Any]) -> tuple[int, int]:
    path = project_root / item["file"]
    if not path.exists():
        raise ValueError(f"{item['id']}: missing file {item['file']}")
    lines = path.read_text(encoding="utf-8", errors="ignore").splitlines()
    line = _find_line(lines, str(item["function"]), str(item["line_hint"]))
    file_text = "\n".join(lines).lower()
    missing = [kw for kw in item["keywords"] if str(kw).lower() not in file_text]
    if missing:
        raise ValueError(f"{item['id']}: keywords not found in {item['file']}: {missing}")
    return line, line


def _entry_function(project_root: Path, seed_item: dict[str, Any]) -> str:
    if seed_item["entry_kind"] in {"mapper", "project_file"}:
        return str(seed_item["function"])
    file_path = str(seed_item["file"])
    package = ""
    text_path = project_root / file_path
    if text_path.exists():
        for line in text_path.read_text(encoding="utf-8", errors="ignore").splitlines()[:20]:
            if line.startswith("package "):
                package = line.split("package ", 1)[1].rstrip(";").strip()
                break
    class_name = Path(file_path).stem
    prefix = f"{package}.{class_name}" if package else class_name
    return f"{prefix}.{seed_item['function']}"


def _build_manifests_from_seeds(
    project_root: Path,
    seeds: list[dict[str, Any]],
    *,
    benchmark: str,
    version: str,
    include_tier_fields: bool,
    default_include_tiers: list[str] | None = None,
) -> tuple[dict[str, Any], dict[str, Any]]:
    vulnerabilities: list[dict[str, Any]] = []
    entries: dict[str, dict[str, Any]] = {}
    rule_ids: set[str] = set()
    categories: set[str] = set()
    cwes: set[str] = set()
    tiers: set[str] = set()

    for raw in seeds:
        item = dict(raw)
        tier = str(item.get("gt_tier") or "core_static")
        line, end_line = _validate_seed(project_root, item)
        rule_ids.add(item["rule_id"])
        categories.add(item["category"])
        cwes.add(item["cwe"])
        tiers.add(tier)
        sink = {
            "description": item["sink"],
            "file": item["file"],
            "line": line,
            "line_hint": item["line_hint"],
        }
        vuln = {
            "id": item["id"],
            "rule_id": item["rule_id"],
            "cwe": item["cwe"],
            "category": item["category"],
            "title": item["title"],
            "file": item["file"],
            "function": item["function"],
            "line": line,
            "end_line": end_line,
            "severity": item["severity"],
            "keywords": item["keywords"],
            "route": item["route"],
            "scenario": item["title"],
            "source": item["source"],
            "sink": sink,
            "official_refs": OFFICIAL_REFS,
            "fix_refs": item["fix_refs"],
            "gt_tier": tier,
        }
        vulnerabilities.append(vuln)

        entry_name = _entry_function(project_root, item)
        entry_payload = {
            "function": entry_name,
            "file": item["file"],
            "entry_kind": item["entry_kind"],
            "component": item["component"] or "unknown",
            "routes": [],
            "covers_gt_ids": [],
            "covers_categories": [],
        }
        if include_tier_fields:
            entry_payload["covers_tiers"] = []
        entry = entries.setdefault(entry_name, entry_payload)
        if item["route"] not in entry["routes"]:
            entry["routes"].append(item["route"])
        entry["covers_gt_ids"].append(item["id"])
        if item["category"] not in entry["covers_categories"]:
            entry["covers_categories"].append(item["category"])
        if include_tier_fields and tier not in entry["covers_tiers"]:
            entry["covers_tiers"].append(tier)

    vulnerabilities.sort(key=lambda item: item["id"])
    entry_values = sorted(entries.values(), key=lambda item: item["function"])
    for entry in entry_values:
        entry["covers_gt_ids"] = sorted(entry["covers_gt_ids"])
        entry["covers_categories"] = sorted(entry["covers_categories"])
        entry["routes"] = sorted(entry["routes"])
        if include_tier_fields and "covers_tiers" in entry:
            entry["covers_tiers"] = sorted(entry["covers_tiers"])

    coverage_by_category: dict[str, int] = defaultdict(int)
    coverage_by_tier: dict[str, int] = defaultdict(int)
    for vuln in vulnerabilities:
        coverage_by_category[str(vuln["category"])] += 1
        coverage_by_tier[str(vuln.get("gt_tier") or "core_static")] += 1

    coverage: dict[str, Any] = {
        "rule_ids": sorted(rule_ids),
        "security_categories": sorted(categories),
        "cwes": sorted(cwes),
        "by_category": dict(sorted(coverage_by_category.items())),
        "excluded_scope": [
            "unconfirmed official scenarios without stable source coordinates",
            "third-party static assets without project-specific source/sink notes",
            "traffic/pcap examples that only document packets and not vulnerable code",
        ],
    }
    if include_tier_fields:
        coverage["gt_tiers"] = sorted(tiers)
        coverage["by_tier"] = dict(sorted(coverage_by_tier.items()))
    else:
        coverage["gt_tier"] = "core_static"
        coverage["excluded_scope"] = [
            "DOM-only frontend sinks",
            "pure frontend component scenarios",
            "traffic/pcap-only confirmations",
            "runtime-only exploitability checks without stable static coordinates",
        ]
    truth = {
        "benchmark": benchmark,
        "suite": "javaseclab",
        "language": "java",
        "version": version,
        "coverage": coverage,
        "total_vulnerabilities": len(vulnerabilities),
        "vulnerabilities": vulnerabilities,
        "safe_entries": [],
    }
    if default_include_tiers:
        truth["scoring"] = {
            "default_include_tiers": default_include_tiers,
            "tier_policy": "core_static remains the formal score; extended/runtime/frontend tiers are observation layers unless explicitly included.",
        }
    entries_manifest = {
        "benchmark": benchmark,
        "suite": "javaseclab",
        "language": "java",
        "version": truth["version"],
        "entries": entry_values,
    }
    return truth, entries_manifest


def build_manifests(project_root: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    return _build_manifests_from_seeds(
        project_root,
        SEEDS,
        benchmark="zscope-javaseclab-core",
        version="2026-07-06-core-static-v1",
        include_tier_fields=False,
    )


def build_extended_manifests(project_root: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    return _build_manifests_from_seeds(
        project_root,
        SEEDS + EXTENDED_SEEDS,
        benchmark="zscope-javaseclab-extended",
        version="2026-07-07-layered-v1",
        include_tier_fields=True,
        default_include_tiers=["core_static"],
    )


def _write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _check_file(path: Path, payload: dict[str, Any]) -> None:
    expected = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    if not path.exists():
        raise SystemExit(f"Missing generated file: {path}")
    actual = path.read_text(encoding="utf-8")
    if actual != expected:
        raise SystemExit(f"Generated manifest drifted: {path}. Run scripts/generate_javaseclab_ground_truth.py")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, default=DEFAULT_PROJECT_ROOT)
    parser.add_argument("--check", action="store_true", help="validate generated files without rewriting them")
    args = parser.parse_args(argv)

    project_root = args.project_root.resolve()
    truth, entries = build_manifests(project_root)
    extended_truth, extended_entries = build_extended_manifests(project_root)
    benchmark_root = project_root / BENCHMARK_DIR
    truth_path = benchmark_root / "ground_truth.json"
    entries_path = benchmark_root / "entries.json"
    extended_truth_path = benchmark_root / "ground_truth_extended.json"
    extended_entries_path = benchmark_root / "entries_extended.json"
    if args.check:
        _check_file(truth_path, truth)
        _check_file(entries_path, entries)
        _check_file(extended_truth_path, extended_truth)
        _check_file(extended_entries_path, extended_entries)
        print(
            "JavaSecLab ground truth is up to date: "
            f"{truth['total_vulnerabilities']} core vulnerabilities, "
            f"{extended_truth['total_vulnerabilities']} layered vulnerabilities"
        )
        return 0

    _write_json(truth_path, truth)
    _write_json(entries_path, entries)
    _write_json(extended_truth_path, extended_truth)
    _write_json(extended_entries_path, extended_entries)
    print(f"Wrote {truth_path} with {truth['total_vulnerabilities']} vulnerabilities")
    print(f"Wrote {entries_path} with {len(entries['entries'])} entries")
    print(f"Wrote {extended_truth_path} with {extended_truth['total_vulnerabilities']} vulnerabilities")
    print(f"Wrote {extended_entries_path} with {len(extended_entries['entries'])} entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
